-- `location_areas` was seeded in 0078 from the map's pin gazetteer — 41 rows,
-- all of them inside Addis Ababa, chosen because a property listing needed a
-- coordinate. That is a different question from "where do you work", and it
-- showed: somebody in Ayertena, in Piassa, in Merkato, in Adama or in Bahir
-- Dar could not say so. A profile field with no row for where you live is a
-- field you leave empty.
--
-- So the table gets the rest of the city and the rest of the country. The rows
-- below are generated from `src/lib/location/places.ts`, which is the one list
-- the application reads, and `scripts/places_check.ts` asserts the two still
-- match line for line — a directory kept in two places is a directory that
-- drifts, and this is the second time that has had to be said in this file's
-- history.
--
-- Regions are deliberately absent. A service area is somewhere you would
-- travel to for one job; "Oromia" is not that, so a region is offered as a
-- base location in the application and has no row here.
--
-- Additive only: no row is deleted or renamed, so every existing
-- `professional_service_areas` row still points at the area it always did.
-- `on conflict do nothing` on the natural key makes re-running it free.

